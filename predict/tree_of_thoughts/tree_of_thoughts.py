class Response(BaseModel):
	"""A final response generated by the Tree-Of-Thoughts program.

	The response is a dictionary mapping output field names (from the generator signature)
	to their values. The structure depends on the generator signature's output fields.
	"""

	response_data: dict[str, Any] = Field(
		...,
		description="Dictionary containing response data with output field names as keys.",
	)

	@classmethod
	def from_dict(cls, data: dict[str, Any]) -> "Response":
		"""Create a Response from a dictionary."""
		return cls(response_data=data)

	def to_dict(self) -> dict[str, Any]:
		"""Convert Response back to dictionary."""
		return self.response_data


class TreeOfThoughtsOutput(BaseModel):
	"""
	A prediction generated by the Tree-Of-Thoughts program.

	The prediction includes a collection of candidate final responses, the reasoning chains that
	led to these responses, the reasoning tree from which the responses were derived, the cost of
	running the tree of thoughts, and the runtime of the tree of thoughts.
	"""

	responses: list[Response] = Field(
		..., description="A collection of final responses.", alias=ToTField.RESPONSES
	)
	reasoning_steps: list[ReasoningChain] = Field(
		...,
		description="A collection of reasoning chains that led to the answer.",
		alias=ToTField.REASONING_STEPS,
	)
	response_strings: list[str] = Field(
		...,
		description="A collection of final responses formatted as strings.",
		alias=ToTField.RESPONSE_STRINGS,
	)
	tree: Tree = Field(
		...,
		description="The reasoning tree from which the final responses were derived.",
		alias=ToTField.TREE,
	)
	# TODO[P3]: Add support for cost calculation if using API calls to open-source models
	# as opposed to hosting them locally.
	cost: float | None = Field(
		default=None,
		description="The cost of running the tree of thoughts (in USD).",
		alias=ToTField.COST,
	)
	runtime: float = Field(
		...,
		description="The runtime of the tree of thoughts (in seconds).",
		alias=ToTField.RUNTIME,
	)


def build_tree_log_payload(
	tree: Tree,
	tot_parameters: TreeOfThoughtsParameters,
	tot_output: TreeOfThoughtsOutput,
) -> dict[str, Any]:
	"""Create a JSON-serializable payload capturing the full Tree of Thoughts run."""
	tree_payload = tree.tree_to_json()
	output_payload = []
	for index, (response, chain) in enumerate(
		zip(tot_output.responses, tot_output.reasoning_steps, strict=True)
	):
		output_payload.append(
			{
				"response": response.to_dict(),
				"response_string": tot_output.response_strings[index],
				"reasoning_chain": [node.model_dump() for node in chain.nodes],
			}
		)
	return {
		"tree_of_thoughts_parameters": asdict(tot_parameters),
		"tree_outputs": output_payload,
		"tree_metadata": {
			"runtime_seconds": tot_output.runtime,
			"cost": tot_output.cost,
		},
		"tree": tree_payload,
	}


def log_tree_run(
	tree: Tree,
	tot_parameters: TreeOfThoughtsParameters,
	tot_output: TreeOfThoughtsOutput,
	directory_path: str | None = None,
	file_name: str | None = None,
) -> dict[str, Any]:
	"""
	Serialize and persist a Tree of Thoughts run.

	Parameters:
	    tree: Tree structure to serialize.
	    tot_parameters: Parameters used for the run.
	    tot_output: Final outputs and reasoning chains.
	    directory_path: Optional directory for the log.
	    file_name: Optional filename for the log. If provided and include_date_time
			is True, a timestamp will be appended before the file extension.

	Returns:
	    Dict containing the serialized run.
	"""
	payload = build_tree_log_payload(
		tree=tree,
		tot_parameters=tot_parameters,
		tot_output=tot_output,
	)
	# Determine the actual filename that will be saved (with timestamp if applicable)
	actual_file_name = file_name
	if file_name is not None:
		timestamp = time.strftime("%Y-%m-%d_%H-%M-%S")
		if file_name.endswith(".json"):
			actual_file_name = f"{file_name[:-5]}_{timestamp}.json"
		else:
			actual_file_name = f"{file_name}_{timestamp}.json"
	elif file_name is None:
		actual_file_name = f"additive_reasoning_tree_{time.strftime('%Y-%m-%d_%H-%M-%S')}.json"

	Tree.save_json_to_file(
		tree_json=payload,
		directory_path=directory_path,
		file_name=file_name,
		include_date_time=True,
	)
	logger.info(f"Saved tree to {directory_path}/{actual_file_name}")
	return payload


class TreeOfThoughts(dspy.Module):
	"""Utilizes Tree-of-Thoughts to answer complex reasoning tasks.

	In our notation, given some input problem, `x`, the model is tasked with producing thoughts,
	`Z := [z_1, ..., z_n]` in order to generate a high-quality final response, `y`, for the task.

	Each `z` is a reasoning step towards `y`, where `z_i` denotes the `i`-th reasoning step in a
	reasoning chain `Z`.
	The final response, `y`, is derived from both the input, `x`, and the intermediate reasoning
	steps, `z_1, ..., z_n` (where `n` is the pre-defined number of reasoning steps to take).

	Each new intermediate reasoning step (`z`) should help (or increase the likelihood of)
	producing a high-quality final response, `y`, for the task.

	The generator creates `m` candidates for each reasoning step:
	`Z_i := [z_(i, 1), z_(i, 2), ..., z_(i, m)]`, where `m` is the number of samples to generate.
	Each of these `m` candidates is evaluated, and only the `top_k` highest-scoring candidates
	are explored further. The value for `m` is controlled by the `n_samples_generation` parameter.

	Once we have `m` candidates for each reasoning step, we evaluate them using the evaluator.
	The evaluator assigns a quality score to each candidate based on task-specific criteria.
	The top-k candidates are then selected for further expansion in the tree.
	The value for `k` is controlled by the `top_k` parameter.

	The process continues for `n` reasoning steps, where `n` is the depth of the tree.
	The final `1 <= l <= k` final response(s), `y`, are derived from the highest-scoring reasoning
	chain(s) (if any).
	"""

	def _set_lm(
		self,
		generative_lm: GenerativeLocalVLLM | None,
		reranker_lm: ScoringLocalVLLM | None = None,
	) -> GenerativeLocalVLLM:
		"""
		Set the language model for the Tree-Of-Thoughts module.

		Sets the LM for generator, evaluator, and controller.

		Parameters:
			generative_lm (GenerativeLocalVLLM | None): The language model to use for the generator,
				evaluator, and controller (if controller_type is GENERATOR). Falls back to
				dspy.settings.lm if None.
			reranker_lm (ScoringLocalVLLM | None): The language model to use for the reranker
				controller.

		Returns:
			The generative language model instance.

		Raises:
			AssertionError: If the language model is not a GenerativeLocalVLLM instance or is None.
			ValueError: If using a reranker controller and the reranker language model is not provided.
			ValueError: If an invalid controller type is provided.
		"""
		generative_lm = generative_lm if generative_lm is not None else dspy.settings.lm
		assert generative_lm is not None, "generative_lm must not be None"
		assert isinstance(generative_lm, GenerativeLocalVLLM), (
			"generative_lm must be a GenerativeLocalVLLM instance"
		)
		self.generator.lm = generative_lm
		if self.evaluator_type == "generator":
			self.evaluator.process_evaluator.set_lm(generative_lm)
			self.evaluator.outcome_evaluator.set_lm(generative_lm)
		elif self.evaluator_type == "programmatic":
			pass
		else:
			if reranker_lm is None or not isinstance(reranker_lm, ScoringLocalVLLM):
				raise ValueError(
					"reranker_lm must be provided when evaluator_type is RERANKER. "
					"Please initialize a ScoringLocalVLLM and pass it as reranker_lm.\n"
					f"Got {reranker_lm} of type {type(reranker_lm)}."
				)
			self.evaluator.set_lm(reranker_lm)
		# Set controller LM for both generator and reranker controllers
		if self.controller_type == "generator":
			self.controller.set_lm(generative_lm)
		elif self.controller_type == "reranker":
			if reranker_lm is None or not isinstance(reranker_lm, ScoringLocalVLLM):
				raise ValueError(
					"reranker_lm must be provided when controller_type is RERANKER. "
					"Please initialize a ScoringLocalVLLM and pass it as reranker_lm.\n"
					f"Got {reranker_lm} of type {type(reranker_lm)}."
				)
			self.controller.set_lm(reranker_lm)
		else:
			raise ValueError(f"Invalid controller type: {self.controller_type}")
		return generative_lm

	@staticmethod
	def _set_seed(seed: int) -> int:
		"""
		Set the random seed for reproducibility.

		Parameters:
			seed (int): The random seed to use for reproducibility.

		Returns:
			The random seed.
		"""
		random.seed(seed)
		np.random.seed(seed)
		torch.manual_seed(seed)
		return seed

